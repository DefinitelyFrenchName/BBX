def family_modules(root):
    """family word -> the bbx modules `lib/sh/compare.sh` reaches for it.

    Read from the dispatcher's own case and its functions, so a new family is
    a new row there and nowhere else (R23)."""
    p = os.path.join(root, "lib", "sh", "compare.sh")
    if not os.path.exists(p):
        return {}
    src = open(p, errors="replace").read()
    funcs = dict(re.findall(r"(?m)^([a-z_][a-z0-9_]*)\(\)\s*\{\n(.*?)\n\}", src, re.S))
    fam2fn = dict(re.findall(r"(?m)^\s+([a-z-]+)\)\s+(compare_[a-z]+)\s", src))

    def mods(fn, seen):
        if fn in seen or fn not in funcs:
            return set()
        seen.add(fn)
        body = funcs[fn]
        found = set(re.findall(r"bbx\.([a-z_]+)", body))
        for other in funcs:
            if other != fn and re.search(r"(^|[;&|(\s])" + other + r"(\s|$)", body, re.M):
                found |= mods(other, seen)
        return found
    return {fam: mods(fn, set()) for fam, fn in fam2fn.items()}


def named_by_kind(root, univ):
    """letter -> the universe files that kind's profile and consumers NAME."""
    fams = family_modules(root)
    inuniv = set(univ)
    named = {L: set() for L in LETTER.values()}

    def add(letter, rel):
        if rel in inuniv:
            named[letter].add(rel)

    for kind, letter in LETTER.items():
        prof = C.KINDS.get(kind, {})
        rows = prof.get("expectations", {}).get("kinds") or C.DEFAULTS["expectations"]["kinds"]
        for fam in {r[1] for r in rows if r[1] in fams}:
            for m in fams[fam]:
                add(letter, f"lib/py/bbx/{m}.py")
        suite = prof.get("suite", {})
        for m in re.findall(r"bbx\.([a-z_]+)", suite.get("log_summary", "") or ""):
            add(letter, f"lib/py/bbx/{m}.py")
        add(letter, driver_rel(suite.get("driver")))
    for cpath in git(root, "ls-files", "*bbx.toml").split():
        if cpath == "bbx.toml":
            continue
        try:
            cfg = C.load(os.path.join(root, cpath))
            kind = C.kind_of(cfg)
        except Exception:
            continue
        if kind in LETTER:
            add(LETTER[kind], driver_rel(cfg.get("suite", {}).get("driver")))
    return named


def driver_rel(value):
    """A bare driver NAME is ours; a path names another tree's (R26) and is
    outside this universe, so it is dropped rather than mangled."""
    if not value or "/" in value:
        return ""
    return f"drivers/{value}.sh"


def seeds(root, univ):
    named = named_by_kind(root, univ)
    out = {}
    for L in named:
        others = set().union(*[named[o] for o in named if o != L]) if len(named) > 1 else set()
        out[L] = named[L] - others
    return out


def importers(root, univ):
    """module relpath -> the universe modules that IMPORT it, transitively.

    The trace's python half records what was LOADED, not what was run (the
    instrument's declared limit), so a seed hit can be the side effect of a
    SHARED module's import. Measured at bbx-19: `compare_exact.py` and
    `compare_set.py` both import `docset.py`, so the document-set seed fired on
    `gates/adapters.sh` — a command-line gate — and it read `DC`. The third kind
    is the detector of exactly this, which is BBX-25's own argument.

    bbx-11 could not see it: with two kinds, every gate that ran the exact
    family was a document-set gate, so the wrong attribution was invisible."""
    direct = {}
    for rel in univ:
        if not rel.startswith("lib/py/bbx/") or not rel.endswith(".py"):
            continue
        src = open(os.path.join(root, rel), errors="replace").read()
        names = set(re.findall(r"^\s*from \.(?:\s*)import ([a-z_][a-z0-9_]*)", src, re.M))
        names |= set(re.findall(r"^\s*from \.([a-z_][a-z0-9_]*) import", src, re.M))
        names |= set(re.findall(r"^\s*import bbx\.([a-z_][a-z0-9_]*)", src, re.M))
        direct[rel] = {f"lib/py/bbx/{n}.py" for n in names} & set(univ)
    closure = {}
    for rel in direct:
        seen, todo = set(), list(direct[rel])
        while todo:
            m = todo.pop()
            if m in seen:
                continue
            seen.add(m)
            todo.extend(direct.get(m, ()))
        closure[rel] = seen
    out = {}
    for rel, imported in closure.items():
        for m in imported:
            out.setdefault(m, set()).add(rel)
    return out


# ----------------------------------------------------- the shadow and its trace

def header_end(lines):
    """The last line of the LEADING COMMENT BLOCK after the shebang (R30).

    0 when there is none — the caller then inserts after the shebang and the
    file has no header to end. A bare `#` continues the block; the first
    non-comment line ends it."""
    last = 0
    for i, line in enumerate(lines[1:], start=2):
        if line.startswith("#"):
            last = i
        else:
            break
    return last


def instrument(shadow, trace, univ, after_shebang=False):
    """One trace line per executed sh file; lib/sh files are SOURCED, so their
    line goes at the end. Returns the list of files instrumented."""
    done = []
    execs = [p for p in univ if (p.startswith("bin/") or
                                 (p.startswith("drivers/") and p.endswith(".sh")))]
    sourced = [p for p in univ if p.startswith("lib/sh/") and p.endswith(".sh")]
    for rel in execs:
        path = os.path.join(shadow, rel)
        if not os.path.exists(path):
            continue
        lines = open(path, errors="replace").read().splitlines(keepends=True)
        if not lines:
            continue
        n = 1 if after_shebang else (header_end([l.rstrip("\n") for l in lines]) or 1)
        probe = "printf '%%s\\n' '%s' >> '%s'\n" % (rel, trace)
        with open(path, "w") as f:
            f.writelines(lines[:n])
            f.write(probe)
            f.writelines(lines[n:])
        os.chmod(path, 0o755)
        done.append(rel)
    for rel in sourced:
        path = os.path.join(shadow, rel)
        if not os.path.exists(path):
            continue
        with open(path, "a") as f:
            f.write("\nprintf '%%s\\n' '%s' >> '%s'\n" % (rel, trace))
        done.append(rel)
    site = os.path.join(shadow, "lib", "py", "sitecustomize.py")
    if os.path.isdir(os.path.dirname(site)):
        with open(site, "w") as f:
            f.write(SITECUSTOMIZE % {"trace": trace, "root": shadow + os.sep})
        done.append("lib/py/sitecustomize.py")
    return done


SITECUSTOMIZE = '''\
import atexit, os, sys
_T = %(trace)r
# REALPATH on both sides, never the path as written. A gate derives its own home
# with `cd "$(dirname "$0")/.." && pwd`, and what `pwd` reports depends on how the
# gate was started: with a cwd handed to the process (no matching PWD in its
# environment) the shell reports the PHYSICAL path, so on macOS a shadow under
# TMPDIR is imported as /private/var/... while the instrument had written
# /var/... and startswith() was False for EVERY module. Measured at bbx-19: 30 of
# 44 harness files read as "executed by NO gate" — a plausible number and pure
# garbage (BBX-16). The same run under build/ traced correctly only because no
# symlink lies in that path, which is luck, not design.
_ROOT = os.path.realpath(%(root)r) + os.sep
def _keep(p, seen):
    if not p:
        return
    r = os.path.realpath(p)
    if r.startswith(_ROOT) and "/lib/py/bbx/" in r:
        seen.add(os.path.relpath(r, _ROOT))
def _dump():
    seen = set()
    for m in list(sys.modules.values()):
        _keep(getattr(m, "__file__", None), seen)
    _keep(sys.argv[0] if sys.argv else "", seen)
    if seen:
        with open(_T, "a") as fh:
            for s in sorted(seen):
                print(s, file=fh)   # no escape here on purpose: a newline escape in this template collapsed one level and broke the emitted file (bbx-19)
atexit.register(_dump)
'''


def build_shadow(root, out, univ, after_shebang=False, refreeze=""):
    shadow = os.path.join(out, "shadow")
    trace = os.path.join(out, "trace.txt")
    if os.path.exists(shadow):
        subprocess.run(["rm", "-rf", shadow], check=True)
    os.makedirs(shadow)
    tar = subprocess.Popen(["git", "-C", root, "archive", "HEAD"], stdout=subprocess.PIPE)
    subprocess.run(["tar", "-x", "-C", shadow], stdin=tar.stdout, check=True)
    tar.stdout.close()
    tar.wait()
    head = identity(root)
    commit = git(root, "rev-parse", "HEAD").strip()
    instrumented = instrument(shadow, trace, univ, after_shebang)
    sh_commit(shadow, "shadow-instrumented")
    if refreeze:
        # A subject whose OWN expectations are keyed by its content (R38's
        # identity) is legitimately MOVED by instrumentation: BBX's
        # fixture/selfgates reads "THE HARNESS HAS MOVED" and gates/adapters.sh
        # FAILs in the shadow, which the refusal above would then read as a
        # contaminated trace (measured at bbx-19, exit 1 on `--only adapters`).
        # So the subject is given one command to re-derive those expectations
        # INSIDE the throwaway shadow, after the first commit because the key is
        # of the COMMIT. The four identity trees are untouched by such a
        # regeneration, so the key is stable across the second commit.
        env = {**os.environ, "BBX_HOME": shadow,
               "PYTHONPATH": os.path.join(shadow, "lib", "py")}
        r = run(["sh", "-c", refreeze], cwd=shadow, env=env)
        print(f"  refreeze   `{refreeze}` in the shadow: exit {r.returncode}")
        if r.returncode:
            for line in (r.stdout + r.stderr).splitlines()[-6:]:
                print(f"      {line}")
            raise RuntimeError(f"--shadow-refreeze failed (exit {r.returncode})")
        sh_commit(shadow, "shadow-refrozen")
    return shadow, trace, head, commit, instrumented


def sh_commit(shadow, message):
    run(["git", "-C", shadow, "init", "-q"])
    run(["git", "-C", shadow, "add", "-A"])
    run(["git", "-C", shadow, "-c", "user.name=fc", "-c", "user.email=fc@fc",
         "commit", "-qm", message])


# ------------------------------------------------------------ running the gates

def harness_home():
    """The HARNESS's own root, never the subject's: the classifier that reads a
    shadow gate's verdict is BBX's (the stronger copy, [BBH-82]), so a synthetic
    subject tree needs no `bin/bbx` of its own."""
    return os.environ.get("BBX_HOME") or os.path.dirname(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))


def classify(rc, log):
    home = harness_home()
    r = run([os.path.join(home, "bin", "bbx"), "classify", str(rc), log],
            env={**os.environ, "PYTHONPATH": os.path.join(home, "lib", "py")})
    text = (r.stdout or r.stderr).strip()
    return text.split("\t")[0].split()[0] if text else "?"


def run_gates(shadow, trace, out, names, extra_env):
    os.makedirs(os.path.join(out, "files"), exist_ok=True)
    os.makedirs(os.path.join(out, "logs"), exist_ok=True)
    rows = []
    for name in names:
        gate = os.path.join(shadow, "gates", f"{name}.sh")
        log = os.path.join(out, "logs", f"{name}.log")
        files = os.path.join(out, "files", f"{name}.txt")
        if os.path.exists(trace):
            os.remove(trace)
        if not os.path.exists(gate):
            open(files, "w").close()
            open(log, "w").write(f"MISSING: {gate}\n")
            rows.append((name, 1, 0, "MISSING"))
            continue
        # BBX_FILE_CENSUS_SHADOW tells a gate it is inside an instrumented shadow, so a gate
        # whose question is UNANSWERABLE there can SKIP and say why. Measured at bbx-20: the
        # instrument writes lib/py/sitecustomize.py and `git add -A` commits it, so the
        # shadow's universe permanently holds a harness file the tree's census register can
        # never contain — gates/census_register.sh therefore read FAIL in every shadow, the
        # contamination rule discarded the run, and the register could only be completed by a
        # run that could not complete (G46).
        env = {**os.environ, "PYTHONPATH": os.path.join(shadow, "lib", "py"),
               "PYTHONDONTWRITEBYTECODE": "1", "BBX_FILE_CENSUS_SHADOW": "1", **extra_env}
        t0 = time.time()
        r = run(["sh", os.path.join("gates", f"{name}.sh")], cwd=shadow, env=env)
        secs = int(round(time.time() - t0))
        open(log, "w").write(r.stdout + r.stderr)
        seen = sorted(set(open(trace).read().split())) if os.path.exists(trace) else []
        open(files, "w").write("".join(s + "\n" for s in seen))
        rows.append((name, r.returncode, secs, classify(r.returncode, log)))
    with open(os.path.join(out, "verdicts.tsv"), "w") as f:
        f.write("gate\texit\tseconds\tverdict\n")
        for name, rc, secs, v in rows:
            f.write(f"{name}\t{rc}\t{secs}\t{v}\n")
    return rows


def read_run(out):
    """A KEPT run read back: the identity, every gate's verdict, and how many
    files were instrumented — all three, because a render under `--reuse` needs
    the instrumented count for row A4 and read it as unset on its first try
    (UnboundLocalError, caught by this gate's own regeneration at bbx-19). `--reuse`
    exists so a gate that costs minutes can run its CONTROLS against the same
    measurement instead of re-measuring once per control (the alternative was
    one whole battery per control)."""
    run_txt = os.path.join(out, "run.txt")
    if not os.path.exists(run_txt):
        raise RuntimeError(f"--reuse: {run_txt} is missing — there is no kept run here")
    keys = dict(l.rstrip("\n").split("\t", 1) for l in open(run_txt) if "\t" in l)
    rows = []
    with open(os.path.join(out, "verdicts.tsv")) as f:
        head = f.readline().rstrip("\n").split("\t")
        for line in f:
            cells = dict(zip(head, line.rstrip("\n").split("\t")))
            rows.append((cells["gate"], int(cells["exit"]), int(cells["seconds"]),
                         cells["verdict"]))
    return keys["identity"], rows, int(keys.get("instrumented", 0))


# ----------------------------------------------------------------- the analysis

def gate_kinds(root, out, rows, seed, static_names, needs_env, imps):
    """A seed hit counts only when nothing else in the same trace EXPLAINS it.

    If a module in the trace imports the seed and is not itself a seed of that
    kind, the hit is the importer's side effect and is dropped — otherwise a
    shared comparator that imports one kind's module would file every gate
    under that kind (measured at bbx-19 on `gates/adapters.sh`)."""
    kinds = {}
    all_seeds = set().union(*seed.values()) if seed else set()
    for name, _rc, _s, _v in rows:
        p = os.path.join(out, "files", f"{name}.txt")
        executed = set(open(p).read().split()) if os.path.exists(p) else set()
        ks = set()
        for L, files in seed.items():
            for f in files & executed:
                explainers = (imps.get(f, set()) & executed) - all_seeds
                if not explainers:
                    ks.add(L)
                    break
        if name in static_names and needs_env and needs_env in uncomment(
                os.path.join(root, "gates", f"{name}.sh")):
            ks.add("F")
        kinds[name] = ks or {"K"}
    return kinds


def reachability(out, rows, univ):
    reach = {f: [] for f in univ}
    for name, _rc, _s, _v in rows:
        p = os.path.join(out, "files", f"{name}.txt")
        for f in (open(p).read().split() if os.path.exists(p) else []):
            reach.setdefault(f, []).append(name)
    return {f: sorted(gs) for f, gs in reach.items()}


def categorise(univ, reach, kinds):
    cat = {}
    for f in univ:
        gs = reach.get(f, [])
        classes = set()
        for g in gs:
            classes |= kinds.get(g, set())
        for label, test in CATEGORIES:
            if test(classes):
                cat.setdefault(label, []).append((f, len(gs), gs))
                break
    return cat


