def render(out, head, univ, rows, kinds, reach, cat, portable, static, instrumented):
    skipped = sorted(n for n, _rc, _s, v in rows if v == "SKIP")
    def letters(name):
        return "".join(c for c in "KFDC" if c in kinds[name]) or "K"
    L = []
    A = []
    counts = {label: len(v) for label, v in cat.items()}
    khist = {}
    for name in kinds:
        khist[letters(name)] = khist.get(letters(name), 0) + 1
    A.append(("A1", "tracked files under lib/, bin/, drivers/ (README.md excluded) — the universe",
              len(univ), "`git ls-files lib bin drivers | grep -vc '\\.md$'`"))
    A.append(("A2", "registered gates (both tiers)", len(portable) + len(static),
              "`grep -hv '^#' gates/portable.txt gates/static.txt | wc -l`"))
    A.append(("A3", "gates run in the shadow, each once, alone, with a fresh trace",
              len(rows), "§B.1, one row each"))
    A.append(("A4", "harness files instrumented (one trace line each)", len(instrumented),
              "§C: every `bin/*`, `drivers/*.sh`, `lib/sh/*.sh` plus `lib/py/sitecustomize.py`"))
    i = 5
    for word in sorted(khist):
        A.append((f"A{i}", f"gates whose derived kind is `{word}`", khist[word], "§B.1"))
        i += 1
    for label, _t in CATEGORIES:
        if label in counts or label == "REACHED BY NO GATE":
            A.append((f"A{i}", f"files: {label}", counts.get(label, 0), "§B.2"))
            i += 1
    A.append((f"A{i}", "files executed by exactly one gate",
              sum(1 for f in univ if len(reach.get(f, [])) == 1), "§B.2, the `gates` column"))
    i += 1
    A.append((f"A{i}", "files executed by 15 gates or more",
              sum(1 for f in univ if len(reach.get(f, [])) >= 15), "§B.2, the `gates` column"))

    L.append(BEGIN)
    L.append("")
    L.append(f"**Measured at harness identity `{head}`** (R38's whole-set key over `bin`, "
             f"`lib`, `drivers`, `gates` — NOT `HEAD`, so a commit that only rewrites this "
             f"document leaves it checkable) over {len(univ)} tracked files under `lib/`, `bin/`, "
             f"`drivers/` (`*.md` excluded) and {len(rows)} gates, each run ONCE in the shadow "
             f"with a fresh trace. `bbx file-census --check` fails on any line below. "
             + (f"**{len(skipped)} gate(s) SKIPPED in the shadow** and so under-report what "
                f"they reach: {', '.join('`' + g + '`' for g in skipped)}."
                if skipped else "No gate skipped in the shadow."))
    L.append("")
    L.append("## A. Counts")
    L.append("")
    L.append("| id | dimension | count | command / derivation |")
    L.append("|---|---|---|---|")
    for idv, dim, n, how in A:
        L.append(f"| {idv} | {dim} | {n} | {how} |")
    L.append("")
    L.append("### B.1 Gates, by derived kind, with the number of harness files each "
             "executed and its verdict in the shadow")
    L.append("")
    # NO SECONDS COLUMN. Runtimes move between runs of the same 30 gates (measured at
    # bbx-19: 12 of 30 rows differed by 1-4 s between two runs whose every file count,
    # kind and verdict was identical), so a checked block carrying them could never be
    # stable and `--check` would fail on every second run — tolerating that difference
    # is exactly what BBX-14 forbids, and the answer is to not freeze a non-deterministic
    # field rather than to excuse it. Per-gate runtimes live in the kept run's
    # verdicts.tsv, which is where a runtime question is answered.
    L.append("| gate | tier | kind | files executed | shadow verdict |")
    L.append("|---|---|---|---|---|")
    for name, _rc, _secs, verdict in rows:
        tier = "portable" if name in portable else "static" if name in static else "-"
        n = len(open(os.path.join(out, "files", f"{name}.txt")).read().split())
        L.append(f"| `{name}` | {tier} | {letters(name)} | {n} | {verdict} |")
    L.append("")
    L.append("### B.2 Files, by category, with every gate that executed them")
    for label, _t in CATEGORIES:
        if label not in cat and label != "REACHED BY NO GATE":
            continue
        L.append("")
        rows_here = cat.get(label, [])
        L.append(f"**{label}: {len(rows_here)}**")
        L.append("")
        if not rows_here:
            L.append("(none)")
            continue
        L.append("| file | gates | executed by |")
        L.append("|---|---|---|")
        for f, n, gs in sorted(rows_here):
            L.append(f"| `{f}` | {n} | {' '.join(gs) or '—'} |")
    L.append("")
    L.append(END)
    return "\n".join(L) + "\n"


def splice(document, block):
    with open(document) as f:
        text = f.read()
    if BEGIN not in text or END not in text:
        raise RuntimeError(f"{document} carries no generated block "
                           f"(expected the BEGIN and END markers)")
    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    return head + block.rstrip("\n") + tail


# ------------------------------------------------- the frozen kind-sets (R39)

def measured_kindsets(univ, reach, kinds):
    out = {}
    for f in univ:
        ks = set()
        for g in reach.get(f, []):
            ks |= kinds.get(g, set())
        out[f] = "".join(c for c in "KFDC" if c in ks)
    return out


def render_frozen(head, kindsets):
    L = ["# expected/file_census.toml — the FROZEN kind-set of every harness file",
         "# (R39; provenance class `self`: BBX's measurement of BBX, which locks",
         "# CURRENCY and never correctness — CLAUDE.md §3.3). Generated by",
         "# `bbx file-census --self --freeze`; compared SHRINK-ONLY: a file that",
         "# lost a kind FAILs naming it, a file reached by NO gate FAILs always,",
         "# a gained kind is a NOTE and re-freezes. Never hand-edited (BBX-21).",
         "",
         "[spec]",
         'class = "self"',
         "# measured_at is R38's whole-set key over bin, lib, drivers, gates — NOT HEAD",
         f'measured_at = "{head}"',
         'mode = "shrink-only"',
         ""]
    for i, (f, ks) in enumerate(sorted(kindsets.items()), start=1):
        L.append(f"[f{i}]")
        L.append(f'file = "{f}"')
        L.append(f'kinds = "{ks}"')
        L.append("")
    return "\n".join(L)


def load_frozen(path):
    from . import toml_subset
    data = toml_subset.load(path)
    rows = {}
    for key, tbl in data.items():
        if key == "spec" or not isinstance(tbl, dict):
            continue
        if "file" not in tbl or "kinds" not in tbl:
            raise RuntimeError(f"{path}: [{key}] needs both `file` and `kinds`")
        if tbl["file"] in rows:
            raise RuntimeError(f"{path}: `{tbl['file']}` frozen twice — hand-editing (BBX-17)")
        rows[tbl["file"]] = tbl["kinds"]
    return data.get("spec", {}), rows


def compare_frozen(frozen, measured):
    """Shrink-only, both ways. Returns (failures, notes)."""
    bad, notes = [], []
    for f in sorted(frozen):
        if f not in measured:
            bad.append(f"FAIL file-census: `{f}` is frozen and is not in the universe "
                       f"(a dead row, BBX-9)")
            continue
        lost = set(frozen[f]) - set(measured[f])
        if lost:
            bad.append(f"FAIL file-census: `{f}` lost kind(s) {''.join(sorted(lost))} "
                       f"— frozen {frozen[f]}, measured {measured[f] or '(no gate)'}")
    for f in sorted(measured):
        if not measured[f]:
            bad.append(f"FAIL file-census: `{f}` is executed by NO gate "
                       f"(rot class 1, orphan)")
        elif f not in frozen:
            notes.append(f"NOTE: file-census-new {f} {measured[f]}")
        else:
            gained = set(measured[f]) - set(frozen[f])
            if gained:
                notes.append(f"NOTE: file-census-grew {f} {''.join(sorted(gained))}")
    return bad, notes



# --------------------------------------- the register's completeness (R47)

def register_completeness(root, frozen_path):
    """The census REGISTER against the universe, both ways, with NO shadow and no
    gate run (R47, ruled 2026-09-12).

    The census itself is release-scoped (D63) because it runs the whole battery
    inside a shadow, so between releases nothing watched it: measured at bbx-20,
    `expected/file_census.toml` and `docs/census/bbx_files.md` are read by
    `gates/file_census.sh` and this module and by nothing else in the battery. A
    harness file added and brought under no gate therefore read green until the
    next release run.

    Two FAILures and one NOTE, the split ruled by the maintainer and following
    R18's own precedent that the register rotting and the world moving are
    different findings:

      FAIL  a universe file with no frozen row — the new-file case, the likeliest
            rot by far, and the one this check exists for
      FAIL  a frozen row naming a file the universe no longer holds (a dead row,
            BBX-9's other direction)
      NOTE  the register's `measured_at` is not the tree's current harness
            identity — the census is STALE, which is true and loud and never
            fatal, because making it fatal would red the battery on every kernel
            commit until a twenty-minute run

    What it CANNOT do, and says so: prove that a file is REACHED by any gate.
    Only a run with traces can, and that is `gates/file_census.sh`'s job."""
    _spec, rows = load_frozen(frozen_path)
    univ = set(universe(root))
    bad, notes = [], []
    for f in sorted(univ - set(rows)):
        bad.append(f"FAIL register: `{f}` is a tracked harness file with NO frozen "
                   f"census row — it may be reached by no gate and nothing would say so")
    for f in sorted(set(rows) - univ):
        bad.append(f"FAIL register: `{f}` has a frozen census row and is not in the "
                   f"universe (a dead row, BBX-9)")
    frozen_at = _spec.get("measured_at", "")
    now = identity(root)
    if frozen_at != now:
        notes.append(f"NOTE: census-drift register={frozen_at[:12]} tree={now[:12]} "
                     f"(the harness moved past the census; the release gate re-measures it)")
    return bad, notes, len(univ), len(rows)

# ------------------------------------------------------------------------- main

def main(argv):
    root = out = document = frozen_path = None
    only = None
    refreeze = ""
    reuse = False
    check_register = False
    after_shebang = check = freeze = False
    extra_env = {}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--self":
            root = os.environ.get("BBX_HOME") or os.getcwd()
        elif a == "--root":
            i += 1
            root = argv[i]
        elif a == "--out":
            i += 1
            out = argv[i]
        elif a == "--document":
            i += 1
            document = argv[i]
        elif a == "--frozen":
            i += 1
            frozen_path = argv[i]
        elif a == "--only":
            i += 1
            only = [x for x in argv[i].split(",") if x]
        elif a == "--env":
            i += 1
            k, _, v = argv[i].partition("=")
            extra_env[k] = v
        elif a == "--shadow-refreeze":
            i += 1
            refreeze = argv[i]
        elif a == "--reuse":
            reuse = True
        elif a == "--check-register":
            check_register = True
        elif a == "--insert-after-shebang":
            after_shebang = True
        elif a == "--check":
            check = True
        elif a == "--freeze":
            freeze = True
        else:
            print(f"bbx file-census: unknown argument {a!r}", file=sys.stderr)
            return 2
        i += 1
    if not root:
        print(__doc__, file=sys.stderr)
        return 2
    root = os.path.abspath(root)
    if not out and not check_register:
        print("bbx file-census: --out DIR is required (the run is kept)", file=sys.stderr)
        return 2
    if out:
        out = os.path.abspath(out)
        os.makedirs(out, exist_ok=True)

    if check_register:
        if not frozen_path:
            print("bbx file-census --check-register needs --frozen PATH", file=sys.stderr)
            return 2
        bad, notes, n_univ, n_rows = register_completeness(root, os.path.abspath(frozen_path))
        for n in notes:
            print(n)
        for b in bad:
            print(b)
        print(f"  register   files {n_univ}   rows {n_rows}   missing-rows "
              f"{len([b for b in bad if 'NO frozen' in b])}   dead-rows "
              f"{len([b for b in bad if 'dead row' in b])}")
        return 1 if bad else 0

    cfg = C.load(os.path.join(root, "bbx.toml"))
    univ = universe(root)
    portable, static = registries(root, cfg)
    names = only if only is not None else portable + static
    seed = seeds(root, univ)
    print(f"  universe   {len(univ)} files   gates {len(names)}   "
          f"seeds F={len(seed['F'])} D={len(seed['D'])} C={len(seed['C'])}")
    if reuse:
        head, rows, n_instr = read_run(out)
        instrumented = ["(kept run)"] * n_instr
        print(f"  reuse      {out}   identity {head[:12]}   {len(rows)} kept traces "
              f"(no shadow built, no gate run)")
    else:
        shadow, trace, head, commit, instrumented = build_shadow(
            root, out, univ, after_shebang, refreeze)
        print(f"  shadow     {shadow} at commit {commit[:12]}   identity {head[:12]}   "
              f"instrumented {len(instrumented)} files"
              f"{'   INSERT-AFTER-SHEBANG (G25 reproduced)' if after_shebang else ''}")
        rows = run_gates(shadow, trace, out, names, extra_env)
        with open(os.path.join(out, "run.txt"), "w") as f:
            f.write(f"identity\t{head}\ncommit\t{commit}\n"
                    f"instrumented\t{len(instrumented)}\n")
        for name, _rc, secs, verdict in rows:
            print(f"    {name:24s} {verdict:8s} {secs}s")
    # A gate that FAILED executed less than it executes in the tree, so its trace is
    # CONTAMINATED and the run is discarded. A gate that SKIPPED asserted nothing and misled
    # nobody, so it does not contaminate — but it DOES under-report its own reach, which is a
    # limit this run STATES rather than absorbs (BBX-30).
    skipped_gates = sorted(n for n, _rc, _s, v in rows if v == "SKIP")
    dirty = [(n, v) for n, _rc, _s, v in rows if v not in ("PASS", "SKIP")]
    if dirty:
        for name, verdict in dirty:
            print(f"REFUSED: file-census: `{name}` is {verdict} in the shadow — its trace is "
                  f"CONTAMINATED, so the run is discarded, never adjusted (CLAUDE.md §1)")
        return 1
    for _g in skipped_gates:
        print(f"NOTE: census-skipped {_g} (it asserted nothing in the shadow, so the files it "
              f"reaches are under-reported by this run)")

    imps = importers(root, univ)
    kinds = gate_kinds(root, out, rows, seed, set(static),
                       C.get(cfg, "registries.static_needs_env"), imps)
    reach = reachability(out, rows, univ)
    cat = categorise(univ, reach, kinds)
    measured = measured_kindsets(univ, reach, kinds)
    print("  gate kinds " + " ".join(
        f"{n}={''.join(c for c in 'KFDC' if c in kinds[n]) or 'K'}" for n, *_ in rows))

    rc = 0
    if frozen_path:
        frozen_path = os.path.abspath(frozen_path)
        if freeze:
            open(frozen_path, "w").write(render_frozen(head, measured))
            print(f"  froze      {len(measured)} kind-set rows into {frozen_path}")
        else:
            try:
                _spec, rows_f = load_frozen(frozen_path)
            except Exception as exc:
                print(f"FAIL file-census: {exc}")
                return 1
            bad, notes = compare_frozen(rows_f, measured)
            for n in notes:
                print(n)
            for b in bad:
                print(b)
            print(f"  kind-sets  frozen {len(rows_f)} measured {len(measured)} "
                  f"failures {len(bad)} notes {len(notes)}")
            if bad:
                rc = 1

    if document:
        document = os.path.abspath(document)
        block = render(out, head, univ, rows, kinds, reach, cat, portable, static, instrumented)
        new = splice(document, block)
        if check:
            old = open(document).read()
            if old == new:
                print(f"  document   {os.path.relpath(document, root)} is the run's own text")
            else:
                a, b = old.splitlines(), new.splitlines()
                for n, (x, y) in enumerate(zip(a, b), start=1):
                    if x != y:
                        print(f"FAIL file-census: {os.path.relpath(document, root)}:{n} "
                              f"differs from the run")
                        print(f"       document: {x}")
                        print(f"       the run : {y}")
                        break
                else:
                    print(f"FAIL file-census: {os.path.relpath(document, root)} has "
                          f"{len(a)} lines, the run renders {len(b)}")
                rc = 1
        else:
            open(document, "w").write(new)
            print(f"  document   {os.path.relpath(document, root)} regenerated "
                  f"({len(block.splitlines())} generated lines)")
    return rc


