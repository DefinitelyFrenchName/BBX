#!/usr/bin/env python3
"""file_census.py — which harness files each GATE EXECUTES, and by the kind of
the gate (BBX-25: a generic thing needs two instances; R39).

    python3 -m bbx.file_census --self   [--out DIR] [--document PATH] [--check]
                                        [--frozen PATH] [--freeze]
    python3 -m bbx.file_census --root DIR --out DIR [--document PATH] [--check]
                                        [--frozen PATH] [--freeze]
                                        [--only g1,g2] [--insert-after-shebang]
                                        [--shadow-refreeze "<command>"] [--reuse]
    python3 -m bbx.file_census --self --frozen PATH --check-register    (cheap: no shadow, R47)

Measured at RUNTIME, never by reading the gates' text. A shadow git tree is
built from the root's HEAD (`git archive`); every `bin/*`, `drivers/*.sh` and
`lib/sh/*.sh` in it gets one line that appends its own path to a trace file,
and a `lib/py/sitecustomize.py` appends every `lib/py/bbx/*.py` module loaded
(and a module run as a script) at interpreter exit. Every registered gate then
runs once, alone, with a fresh trace. A file's CATEGORY is the set of kinds of
the gates that executed it.

WHY NOT A GREP over the gates' text: measured at bbx-19 over this tree, a rule
that reads each gate's consumer configs instead of its trace mis-files FIVE of
29 gates — `gates/config.sh` and `gates/readout.sh` read frame-driven because
their SYNTHETIC fixtures name a `bbh.toml`, and `gates/temporal.sh`,
`gates/thresholds.sh` and `gates/compare_dispatch.sh` read kernel because they
call the temporal comparators directly with no consumer config at all. The
census document's own method paragraph declined the same shortcut at bbx-11 on
the word `masked`. The trace is the instrument; the text is a witness
(BBX-28).

A GATE'S KIND, derived — never a hand list (BBX-9):

  F / D / C   the gate executed a SEED of that kind. A seed is a harness file
              the kind profile NAMES and no other kind profile names: the
              modules its comparator families reach (the families come from
              `[expectations].kinds`, the modules from `lib/sh/compare.sh`'s
              own dispatch case, followed through the functions it calls), the
              module its `[suite].log_summary` names, its `[suite].driver`,
              and the driver of every tracked consumer config of that kind.
  F also      a gate in the STATIC registry whose body, comments stripped,
              names the `[registries].static_needs_env` variable: it needs the
              lineage tree, which is the frame-driven kind's SUBJECT. Measured
              2026-09-12: this reproduces bbx-11's hand list exactly —
              `fidelity_bbh` 4 mentions, `fidelity_bbh_s2` 5, `suite` 10,
              `census_recount` 0.
  K           kernel — BBX as its own subject — when no seed and no need.

Limit, declared rather than discovered: `propose_temporal.py` is not a seed
under this derivation (the proposer is not reached from the dispatcher's case),
where bbx-11's hand list had it. Measured not to matter: all three gates that
execute it also execute `compare_flicker`, `compare_window` and
`compare_composite`, so their kind is unchanged. A kind whose ONLY distinct
module is a proposer would read K and the gate's own rows would say so.

A gate that is not PASS in the shadow CONTAMINATES its trace: the run is
REFUSED (exit 1) naming the gate, never adjusted (CLAUDE.md §1). That refusal
is also the portable gate's control on the instrument — `--insert-after-shebang`
reproduces gotcha G25, where the trace line was inserted right after the
shebang and so ENDED the header under R30, and a gate that reads its own
header's `NOT-ASSERTED:` lines goes red.

First written at bbx-19 (2026-09-12, S4 step 6), lifting the scratchpad
instrument of bbx-11 recorded in `docs/census/bbx_files.md` §C.
"""
